let lang = localStorage.getItem("rg_lang") === "ta" ? "ta" : "en";
const listeners = new Set();

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === "ta" ? "ta" : "en";
  localStorage.setItem("rg_lang", lang);
  document.documentElement.lang = lang === "ta" ? "ta" : "en";
  listeners.forEach((fn) => fn(lang));
}

export function t(s, vars) {
  if (s == null) return "";
  const key = String(s);
  let out = lang === "ta" ? (TA[key] ?? key) : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const raw = v == null ? "" : String(v);
      const shown = lang === "ta" && Object.prototype.hasOwnProperty.call(TA, raw) ? TA[raw] : raw;
      out = out.replaceAll(`{${k}}`, shown);
    }
  }
  return out;
}

export function useLang() {
  const [current, setCurrent] = useState(lang);
  useEffect(() => {
    const fn = (next) => setCurrent(next);
    listeners.add(fn);
    document.documentElement.lang = lang === "ta" ? "ta" : "en";
    return () => listeners.delete(fn);
  }, []);
  return { lang: current, setLang, t };
}
